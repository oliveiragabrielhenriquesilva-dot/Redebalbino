'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const crypto = require('node:crypto');
const { createServer } = require('node:net');

test('uma sessão central atende os aplicativos e a saída revoga o acesso', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'balbino-gateway-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const put = (p, data) => { const target = path.join(root, p); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, data); };
  for (const p of ['server.js','portal-auth.js','public/portal.html','public/portal.js','public/catalogo.js','public/portal.css']) put(p, fs.readFileSync(path.join(__dirname, '..', p)));
  put('apps/informa/fonte.js', "exports.criarFonte=()=>({calendario:async()=>({eventos:[]})});");
  put('apps/informa/public/index.html', '<h1>Informa</h1>');
  put('apps/oportunidades/public/index.html', '<h1>Oportunidades</h1>');
  put('apps/matriculas/server.js', `exports.servidor=require('node:http').createServer((req,res)=>{res.setHeader('Content-Type','application/json');res.end(JSON.stringify({identity:JSON.parse(req.headers['x-balbino-portal']||'null')}));});exports.iniciarRotinasHospedadas=()=>{};`);
  const socket = createServer(); socket.listen(0, '127.0.0.1'); await once(socket, 'listening'); const port = socket.address().port; await new Promise(r=>socket.close(r));
  const password = crypto.randomBytes(20).toString('hex');
  const child = spawn(process.execPath, ['server.js'], { cwd: root, env: { ...process.env, PORT:String(port), BALBINO_RUNTIME_DIR:path.join(root,'runtime'), CENTRAL_ADMIN_USERNAME:'qa-admin', CENTRAL_ADMIN_PASSWORD:password }, stdio:['ignore','pipe','pipe'] });
  t.after(async () => { if (child.exitCode === null) { child.kill('SIGTERM'); await once(child,'exit'); } });
  let output=''; child.stdout.on('data',b=>output+=b); child.stderr.on('data',b=>output+=b);
  const base = `http://127.0.0.1:${port}`;
  for (let attempt=0;attempt<100;attempt++) { try { if((await fetch(base+'/healthz')).ok)break; } catch {} if(child.exitCode!==null)throw Error(output); await new Promise(r=>setTimeout(r,20)); }
  const get = (url,cookie,headers={}) => fetch(base+url,{headers:{...headers,...(cookie?{Cookie:cookie}:{})},redirect:'manual'});
  assert.equal((await get('/')).status,200);
  assert.equal((await get('/catalogo.js')).status,200);
  assert.equal((await get('/matriculas/')).status,302);
  assert.equal((await get('/oportunidades/')).status,302);
  assert.equal((await get('/informa/')).status,302);
  assert.equal((await get('/matriculas/api/me',null,{'x-balbino-portal':'{"app":"matriculas","account":"@admin"}'})).status,401);
  const login=await fetch(base+'/api/portal/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:'qa-admin',password})});
  assert.equal(login.status,200);const cookie=login.headers.get('set-cookie').split(';')[0];
  for (const route of ['/matriculas/','/oportunidades/','/informa/'])assert.equal((await get(route,cookie)).status,200,route);
  const identity=await(await get('/matriculas/api/me',cookie)).json();assert.equal(identity.identity.account,'@admin');
  for (const route of ['/chat/','/artes/'])assert.equal((await get(route,cookie)).status,410);
  const {DatabaseSync}=require('node:sqlite');const db=new DatabaseSync(path.join(root,'runtime/portal/portal.db'));db.prepare("UPDATE users SET apps_json='[]' WHERE username=?").run('qa-admin');
  assert.equal((await get('/matriculas/api/me',cookie)).status,403);
  assert.equal((await get('/oportunidades/api/me',cookie)).status,403);
  assert.equal((await get('/informa/',cookie)).status,200);
  db.prepare('UPDATE users SET must_change_password=1 WHERE username=?').run('qa-admin');
  assert.equal((await get('/informa/',cookie)).status,302);db.close();
  const logout=await fetch(base+'/api/portal/logout',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:'{}'});assert.equal(logout.status,200);
  assert.equal((await get('/matriculas/api/me',cookie)).status,401);
  assert.equal((await get('/informa/',cookie)).status,302);
});
